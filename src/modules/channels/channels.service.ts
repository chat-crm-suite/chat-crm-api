import { Injectable } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { ClsService } from 'nestjs-cls';
import { Repository } from 'typeorm';

import {
  CHANNEL_STATUS,
  CHANNEL_TYPE,
  DEFAULT_WHATSAPP_API_VERSION,
  DEFAULT_WHATSAPP_CHANNEL_NAME,
  WHATSAPP_GRAPH_BASE_URL,
  type ChannelResponse,
  type CreateChannelInput,
  type UpdateChannelInput,
  type WhatsAppConfigResponse,
  type WhatsAppCredentials,
} from '../../contracts/index';
import {
  decryptCredentials,
  encryptCredentials,
} from '../../lib/helpers/credentials.helper';
import { Channel } from './entities/channel.entity';

/** How long a decrypted webhook App Secret lookup is reused. */
const APP_SECRET_CACHE_TTL_MS = 60_000;
/**
 * A miss is reused only briefly: `/setup` creates channels outside this
 * service, so it cannot clear the cache.
 */
const APP_SECRET_MISS_TTL_MS = 5_000;

export interface ChannelTransmission {
  channel: Channel;
  credentials: WhatsAppCredentials;
}

/**
 * Channels: a company talks to customers through N channels. WhatsApp is the
 * first provider; credentials are stored as an AES-256-GCM envelope and only
 * returned (decrypted) by `getWhatsAppConfigWithToken`, for the settings form.
 * Every company is born with a `pending` WhatsApp channel (verify token only);
 * it turns `active` once it has a phone number ID and an access token.
 */
@Injectable()
export class ChannelsService {
  /**
   * phone_number_id → decrypted App Secrets, so a webhook burst does not hit
   * the DB and decrypt on every post. Cleared on any channel write.
   */
  private readonly appSecretCache = new Map<
    string,
    { secrets: string[]; expiresAt: number }
  >();

  constructor(
    @InjectRepository(Channel)
    private readonly channels: Repository<Channel>,
    private readonly cls: ClsService,
  ) {}

  private get companyId(): string {
    return this.cls.get('company.id');
  }

  async list(): Promise<ChannelResponse[]> {
    const rows = await this.channels.find({
      where: { companyId: this.companyId },
      order: { createdAt: 'ASC' },
    });
    return rows.map((channel) => this.sanitize(channel));
  }

  async getWhatsAppConfig(): Promise<ChannelResponse | null> {
    const channel = await this.findWhatsAppChannel();
    return channel ? this.sanitize(channel) : null;
  }

  /** Settings form only: same as `getWhatsAppConfig` plus the decrypted token. */
  async getWhatsAppConfigWithToken(): Promise<WhatsAppConfigResponse | null> {
    const channel = await this.findWhatsAppChannel();
    if (!channel) return null;

    return {
      ...this.sanitize(channel),
      accessToken: this.tryDecrypt(channel.credentials).accessToken || null,
    };
  }

  /** Connection test only: the stored channel with its decrypted credentials. */
  async getWhatsAppTestTarget(): Promise<ChannelTransmission | null> {
    const channel = await this.findWhatsAppChannel();
    if (!channel) return null;
    return { channel, credentials: this.tryDecrypt(channel.credentials) };
  }

  async create(dto: CreateChannelInput): Promise<ChannelResponse> {
    const channel = this.channels.create({
      companyId: this.companyId,
      type: dto.type,
      name: dto.name ?? dto.displayAddress ?? DEFAULT_WHATSAPP_CHANNEL_NAME,
      externalAccountId: dto.externalAccountId,
      displayAddress: dto.displayAddress,
      credentials: encryptCredentials({
        accessToken: dto.accessToken,
        businessId: dto.businessId,
        appSecret: dto.appSecret,
      }),
      settings: {
        apiVersion: dto.apiVersion ?? DEFAULT_WHATSAPP_API_VERSION,
        apiBaseUrl: dto.apiBaseUrl ?? WHATSAPP_GRAPH_BASE_URL,
        webhookUrl: dto.webhookUrl,
      },
      // Empty → generated by the entity on insert.
      webhookVerifyToken: dto.webhookVerifyToken,
      status: CHANNEL_STATUS.active,
    });

    const saved = await this.channels.save(channel);
    this.appSecretCache.clear();
    return this.sanitize(saved);
  }

  async updateWhatsAppConfig(
    dto: UpdateChannelInput,
  ): Promise<ChannelResponse | null> {
    const channel = await this.findWhatsAppChannel();
    if (!channel) return null;

    const patch: Partial<Channel> = {};

    if (dto.name !== undefined) patch.name = dto.name;
    if (dto.displayAddress !== undefined) patch.displayAddress = dto.displayAddress;
    if (dto.externalAccountId !== undefined) {
      patch.externalAccountId = dto.externalAccountId;
    }
    if (dto.webhookVerifyToken !== undefined) {
      patch.webhookVerifyToken = dto.webhookVerifyToken;
    }
    if (dto.status !== undefined) patch.status = dto.status;

    if (
      dto.apiVersion !== undefined ||
      dto.apiBaseUrl !== undefined ||
      dto.webhookUrl !== undefined
    ) {
      const current = (channel.settings ?? {});
      patch.settings = {
        ...current,
        ...(dto.apiVersion !== undefined ? { apiVersion: dto.apiVersion } : {}),
        ...(dto.apiBaseUrl !== undefined ? { apiBaseUrl: dto.apiBaseUrl } : {}),
        ...(dto.webhookUrl !== undefined ? { webhookUrl: dto.webhookUrl } : {}),
      };
    }

    const current = this.tryDecrypt(channel.credentials);
    if (
      dto.accessToken !== undefined ||
      dto.businessId !== undefined ||
      dto.appSecret !== undefined
    ) {
      patch.credentials = encryptCredentials({
        accessToken: dto.accessToken ?? current.accessToken,
        businessId: dto.businessId ?? current.businessId,
        appSecret: dto.appSecret ?? current.appSecret,
      });
    }

    // `pending` → `active` once the channel can send and route.
    const status = patch.status ?? channel.status;
    const accountId = patch.externalAccountId ?? channel.externalAccountId;
    const accessToken = dto.accessToken ?? current.accessToken;
    if (status === CHANNEL_STATUS.pending && accountId && accessToken) {
      patch.status = CHANNEL_STATUS.active;
    }

    return this.updateChannel(channel, patch);
  }

  private async updateChannel(
    channel: Channel,
    patch: Partial<Channel>,
  ): Promise<ChannelResponse> {
    const updated = this.channels.merge(channel, patch);
    await this.channels.save(updated);
    this.appSecretCache.clear();
    return this.sanitize(updated);
  }

  /** Webhook routing: an active channel owns the verify token. */
  async verifyToken(token: string): Promise<boolean> {
    return !!(await this.channels.findOne({
      where: { webhookVerifyToken: token },
      select: { id: true },
    }));
  }

  /**
   * Webhook signature: the App Secrets of every WhatsApp channel registered
   * under this phone_number_id (any status, so callbacks for a paused channel
   * still verify). Empty when none has its own secret: the caller then falls
   * back to the server-wide `WHATSAPP_APP_SECRET`.
   */
  async getWebhookAppSecrets(externalAccountId: string): Promise<string[]> {
    const cached = this.appSecretCache.get(externalAccountId);
    if (cached && cached.expiresAt > Date.now()) return cached.secrets;

    const rows = await this.channels.find({
      where: { externalAccountId, type: CHANNEL_TYPE.whatsapp },
      select: { id: true, credentials: true },
    });
    const secrets = rows
      .map((row) => this.tryDecrypt(row.credentials).appSecret)
      .filter((secret): secret is string => !!secret);

    this.appSecretCache.set(externalAccountId, {
      secrets,
      expiresAt:
        Date.now() +
        (secrets.length ? APP_SECRET_CACHE_TTL_MS : APP_SECRET_MISS_TTL_MS),
    });
    return secrets;
  }

  /** Webhook routing: active WhatsApp channel by phone_number_id. */
  async findActiveByExternalAccountId(
    externalAccountId: string,
  ): Promise<Channel | null> {
    return this.channels.findOne({
      where: {
        externalAccountId,
        type: CHANNEL_TYPE.whatsapp,
        status: CHANNEL_STATUS.active,
      },
    });
  }

  async getTransmissionByExternalAccountId(
    externalAccountId: string,
  ): Promise<ChannelTransmission | null> {
    const channel = await this.findActiveByExternalAccountId(externalAccountId);
    if (!channel?.credentials) return null;

    return {
      channel,
      credentials: decryptCredentials<WhatsAppCredentials>(channel.credentials),
    };
  }

  /** Async enrichment path: the transmission of the conversation's channel. */
  async getTransmissionByChannelId(
    channelId: string,
  ): Promise<ChannelTransmission | null> {
    const channel = await this.channels.findOne({
      where: { id: channelId, type: CHANNEL_TYPE.whatsapp },
    });
    if (!channel?.credentials) return null;

    return {
      channel,
      credentials: decryptCredentials<WhatsAppCredentials>(channel.credentials),
    };
  }

  /** Outbound path: the active WhatsApp channel of a company, decrypted. */
  async getTransmissionForCompany(
    companyId: string,
  ): Promise<ChannelTransmission | null> {
    const channel = await this.channels.findOne({
      where: {
        companyId,
        type: CHANNEL_TYPE.whatsapp,
        status: CHANNEL_STATUS.active,
      },
      order: { createdAt: 'ASC' },
    });
    if (!channel?.credentials) return null;

    return {
      channel,
      credentials: decryptCredentials<WhatsAppCredentials>(channel.credentials),
    };
  }

  private findWhatsAppChannel(): Promise<Channel | null> {
    return this.channels.findOne({
      where: { companyId: this.companyId, type: CHANNEL_TYPE.whatsapp },
      order: { createdAt: 'ASC' },
    });
  }

  private sanitize(channel: Channel): ChannelResponse {
    const settings = (channel.settings ?? {});

    const credentials = this.tryDecrypt(channel.credentials);

    return {
      id: channel.id,
      type: channel.type,
      name: channel.name,
      externalAccountId: channel.externalAccountId ?? null,
      displayAddress: channel.displayAddress ?? null,
      status: channel.status,
      webhookVerifyToken: channel.webhookVerifyToken ?? null,
      apiVersion: (settings.apiVersion as string) ?? null,
      apiBaseUrl: (settings.apiBaseUrl as string) ?? null,
      webhookUrl: (settings.webhookUrl as string) ?? null,
      businessId: credentials.businessId ?? null,
      hasCredentials: !!credentials.accessToken,
      hasAppSecret: !!credentials.appSecret,
      createdAt: channel.createdAt,
      updatedAt: channel.updatedAt,
    };
  }

  private tryDecrypt(stored: string | null): WhatsAppCredentials {
    if (!stored) return { accessToken: '' };
    try {
      return decryptCredentials<WhatsAppCredentials>(stored);
    } catch {
      return { accessToken: '' };
    }
  }
}
