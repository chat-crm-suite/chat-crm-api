import { DataSource, DataSourceOptions, IsNull } from 'typeorm';

import {
  clearSQLiteTables,
  getSQLiteEntities,
  getTestSQLiteConfig,
} from '@helpers/test-database.helper';
import type { MemberRole } from '@contracts';
import { Channel } from '../../channels/entities/channel.entity';
import { CompanyMember } from '../../company-members/entities/company-member.entity';
import { CompanySettings } from '../../company/entities/company-settings.entity';
import { Company } from '../../company/entities/company.entity';
import { Customer } from '../../customers/entities/customer.entity';
import { User } from '../../users/entities/user.entity';
import { ConversationRepository } from '../conversation.repository';
import { ConversationAssignment } from '../entities/conversation-assignment.entity';
import { Conversation } from '../entities/conversation.entity';
import { AssignmentOutcome } from './assignment.types';
import { ConversationAssignmentService } from './conversation-assignment.service';

jest.setTimeout(60_000);

const logger = { setContext: jest.fn(), warn: jest.fn(), debug: jest.fn(), error: jest.fn() };

/**
 * A removed member's conversations go back to the queue and stay eligible for
 * auto-assign; a soft-deleted customer never hides its conversation.
 */
describe('ConversationAssignmentService.releaseAllForMember (integration)', () => {
  let dataSource: DataSource;
  let service: ConversationAssignmentService;
  let company: Company;
  let seq = 0;

  /** `create` first: the UUID v7 id is generated by an entity hook. */
  const save = <T extends object>(entity: new () => T, data: Partial<T>) => {
    const repo = dataSource.getRepository(entity);
    return repo.save(repo.create(data as T));
  };

  beforeAll(async () => {
    dataSource = new DataSource(
      getTestSQLiteConfig(getSQLiteEntities()) as DataSourceOptions,
    );
    await dataSource.initialize();
    service = new ConversationAssignmentService(dataSource, logger as never);
  });

  afterAll(async () => {
    await dataSource.destroy();
  });

  beforeEach(async () => {
    await clearSQLiteTables(dataSource);
    seq = 0;
    company = await save(Company, { name: 'Acme' });
  });

  const seedMember = async (role: MemberRole = 'agent', target = company) => {
    const user = await save(User, { username: `user-${++seq}`, passwordHash: 'x' });
    return save(CompanyMember, {
      userId: user.id,
      companyId: target.id,
      role,
      status: 'active',
    });
  };

  const seedConversation = async (
    owner: CompanyMember | null,
    status: Conversation['status'] = 'open',
    target = company,
  ) => {
    const channels = dataSource.getRepository(Channel);
    const channel =
      (await channels.findOne({ where: { companyId: target.id } })) ??
      (await save(Channel, {
        companyId: target.id,
        type: 'whatsapp',
        name: 'main',
        externalAccountId: `acc-${++seq}`,
        credentials: '{}',
      }));
    const customer = await save(Customer, {
      companyId: target.id,
      displayName: `Cliente ${++seq}`,
    });
    const conversation = await save(Conversation, {
      companyId: target.id,
      customerId: customer.id,
      channelId: channel.id,
      status,
      assignedMemberId: owner?.id ?? null,
      lastMessageAt: new Date(),
    });
    if (owner) {
      await save(ConversationAssignment, {
        conversationId: conversation.id,
        memberId: owner.id,
        reason: 'transfer',
        assignedAt: new Date(Date.now() - 60_000),
      });
    }
    return { conversation, customer };
  };

  it('closes the active assignment, clears the owner and records the release', async () => {
    const leaving = await seedMember();
    const colleague = await seedMember();
    const open = await seedConversation(leaving, 'open');
    const pending = await seedConversation(leaving, 'pending');
    const closed = await seedConversation(leaving, 'closed');
    const archived = await seedConversation(leaving, 'archived');
    const theirs = await seedConversation(colleague, 'open');

    const released = await dataSource.transaction((manager) =>
      service.releaseAllForMember(manager, leaving.id),
    );

    expect(released).toBe(2);
    const conversations = dataSource.getRepository(Conversation);
    const owner = async (id: string) =>
      (await conversations.findOneByOrFail({ id })).assignedMemberId;
    expect(await owner(open.conversation.id)).toBeNull();
    expect(await owner(pending.conversation.id)).toBeNull();
    expect(await owner(closed.conversation.id)).toBe(leaving.id);
    expect(await owner(archived.conversation.id)).toBe(leaving.id);
    expect(await owner(theirs.conversation.id)).toBe(colleague.id);

    const assignments = dataSource.getRepository(ConversationAssignment);
    const rows = await assignments.find({
      where: { conversationId: open.conversation.id },
      order: { assignedAt: 'ASC' },
    });
    // The original row keeps how it began (analytics reads `transfer` from it)
    // and is closed; the release is its own zero-length history row.
    expect(rows.map((row) => row.reason)).toEqual(['transfer', 'release']);
    expect(rows.every((row) => row.unassignedAt)).toBe(true);
    expect(await assignments.count({ where: { memberId: leaving.id, unassignedAt: IsNull() } })).toBe(
      2,
    );

    // Back in the queue, visible to supervisors.
    const queue = await service.listUnassigned(company.id);
    expect(queue.map((item) => item.id).sort()).toEqual(
      [open.conversation.id, pending.conversation.id].sort(),
    );
    expect(await service.getActiveAssignment(open.conversation.id)).toBeNull();
  });

  it('returns the ids too, and is a no-op without open conversations', async () => {
    const leaving = await seedMember();
    const { conversation } = await seedConversation(leaving);

    await expect(service.releaseConversations(company.id, leaving.id)).resolves.toEqual([
      conversation.id,
    ]);
    await expect(service.releaseAllForMember(company.id, leaving.id)).resolves.toBe(0);
    expect(await dataSource.getRepository(ConversationAssignment).count()).toBe(2);
  });

  it('also releases a conversation whose owner column outlived its assignment row', async () => {
    const leaving = await seedMember();
    const { conversation } = await seedConversation(leaving);
    await dataSource
      .getRepository(ConversationAssignment)
      .update({ conversationId: conversation.id }, { unassignedAt: new Date() });

    await expect(service.releaseConversations(company.id, leaving.id)).resolves.toEqual([
      conversation.id,
    ]);
    expect(
      (await dataSource.getRepository(Conversation).findOneByOrFail({ id: conversation.id }))
        .assignedMemberId,
    ).toBeNull();
  });

  it('is scoped by company when given a company id', async () => {
    const leaving = await seedMember();
    await seedConversation(leaving);
    const other = await save(Company, { name: 'Other' });

    await expect(service.releaseAllForMember(other.id, leaving.id)).resolves.toBe(0);
    await expect(service.releaseAllForMember(company.id, leaving.id)).resolves.toBe(1);
  });

  it('rolls back with the caller transaction', async () => {
    const leaving = await seedMember();
    const { conversation } = await seedConversation(leaving);

    await expect(
      dataSource.transaction(async (manager) => {
        await service.releaseAllForMember(manager, leaving.id);
        throw new Error('boom');
      }),
    ).rejects.toThrow('boom');

    expect(
      (await dataSource.getRepository(Conversation).findOneByOrFail({ id: conversation.id }))
        .assignedMemberId,
    ).toBe(leaving.id);
  });

  it('leaves released conversations eligible for auto-assign', async () => {
    await save(CompanySettings, {
      companyId: company.id,
      autoAssignEnabled: true,
      autoAssignMaxOpen: 0,
    });
    const leaving = await seedMember();
    const stays = await seedMember();
    const { conversation } = await seedConversation(leaving);

    await dataSource.getRepository(CompanyMember).softDelete(leaving.id);
    await service.releaseAllForMember(company.id, leaving.id);

    await expect(service.ensureAssigned(conversation.id, company.id)).resolves.toBe(
      AssignmentOutcome.ASSIGNED,
    );
    expect((await service.getActiveAssignment(conversation.id))?.memberId).toBe(stays.id);
  });

  it('never assigns work to a soft-deleted member', async () => {
    await save(CompanySettings, {
      companyId: company.id,
      autoAssignEnabled: true,
      autoAssignMaxOpen: 0,
    });
    const gone = await seedMember();
    await dataSource.getRepository(CompanyMember).softDelete(gone.id);
    const { conversation } = await seedConversation(null);

    await expect(service.ensureAssigned(conversation.id, company.id)).resolves.toBe(
      AssignmentOutcome.NO_CANDIDATES,
    );
    await expect(
      service.assignToAgent(conversation.id, gone.id, { companyId: company.id }),
    ).rejects.toMatchObject({ status: 404 });
    await expect(service.claimForMember(conversation.id, gone.id, company.id)).resolves.toBe(
      AssignmentOutcome.SKIPPED,
    );
  });

  it('keeps the conversations of a soft-deleted customer in the lists', async () => {
    const agent = await seedMember();
    const queued = await seedConversation(null);
    const owned = await seedConversation(agent);
    await dataSource.getRepository(Customer).softDelete([queued.customer.id, owned.customer.id]);

    const queue = await service.listUnassigned(company.id);
    expect(queue.map((item) => item.id)).toEqual([queued.conversation.id]);
    expect(queue[0].customer.displayName).toBe(queued.customer.displayName);

    const repository = new ConversationRepository(dataSource, {} as never);
    const mine = await repository.listForMember(agent.id);
    expect(mine.map((item) => item.id)).toEqual([owned.conversation.id]);
    expect(mine[0].customer.displayName).toBe(owned.customer.displayName);

    // A soft-deleted conversation still disappears.
    await dataSource.getRepository(Conversation).softDelete(owned.conversation.id);
    expect(await repository.listForMember(agent.id)).toEqual([]);
  });
});
