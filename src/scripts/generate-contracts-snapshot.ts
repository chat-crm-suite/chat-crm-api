/**
 * Generates (or checks) the contracts snapshot artifacts.
 *
 * Usage:
 *   pnpm run contracts:snapshot   # writes src/contracts/generated/*.generated.ts
 *   pnpm run contracts:check      # exits 1 when the committed artifacts are stale
 *
 * Outputs (committed, so the app and CI can diff them):
 * - `src/contracts/generated/snapshot.generated.ts` — every contract export as
 *   JSON Schema, grouped by contract file, plus its overall hash.
 * - `src/contracts/generated/version.generated.ts`  — `{ tag, commit, hash,
 *   generatedAt, files }`, where `files` carries a per-file hash + last git
 *   date/version.
 *
 * The artifacts are emitted as `.ts` (not `.json`) so they compile into `dist`
 * and are available at runtime — the production image only ships `dist`. The
 * metadata is derived from git, not `Date.now()`, so `generatedAt` is stable
 * for a given commit and `contracts:check` is deterministic.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { basename, join } from 'node:path';

import { CONTRACT_NAMES, CONTRACT_MODULES } from './contract-registry';
import {
  buildSnapshot,
  serializeSnapshot,
} from './contracts-snapshot';

const GENERATED_DIR = join(process.cwd(), 'src', 'contracts', 'generated');
const SOURCE_DIR = join(process.cwd(), 'src', 'contracts');
const SNAPSHOT_FILE = join(GENERATED_DIR, 'snapshot.generated.ts');
const VERSION_FILE = join(GENERATED_DIR, 'version.generated.ts');

const BANNER =
  '// AUTO-GENERATED by `pnpm run contracts:snapshot` — do not edit by hand.\n';

function sha256(input: Buffer | string): string {
  return createHash('sha256').update(input).digest('hex');
}

/** Runs a git command from the repo root, returning trimmed stdout or null. */
function git(args: string[]): string | null {
  try {
    return execFileSync('git', args, {
      cwd: process.cwd(),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

/** Contract file names present on disk, e.g. `user` for `user.contract.ts`. */
function sourceContractNames(): string[] {
  return readdirSync(SOURCE_DIR)
    .filter((file) => file.endsWith('.contract.ts'))
    .map((file) => basename(file, '.contract.ts'))
    .sort();
}

interface FileMeta {
  hash: string;
  version: string | null;
  updatedAt: string | null;
}

function fileMeta(contractName: string): FileMeta {
  const relPath = `src/contracts/${contractName}.contract.ts`;
  const content = readFileSync(join(SOURCE_DIR, `${contractName}.contract.ts`));

  return {
    hash: sha256(content),
    version: git(['describe', '--tags', '--abbrev=0', '--', relPath]),
    updatedAt: git(['log', '-1', '--format=%cI', '--', relPath]),
  };
}

function buildArtifacts(): { snapshot: string; version: string; hash: string } {
  const onDisk = sourceContractNames();
  const missing = onDisk.filter((name) => !CONTRACT_NAMES.includes(name));

  if (missing.length > 0) {
    throw new Error(
      `Contract(s) not registered in src/scripts/contract-registry.ts: ${missing.join(
        ', ',
      )}`,
    );
  }

  const snapshot = buildSnapshot(CONTRACT_MODULES);
  const serialized = serializeSnapshot(snapshot);
  const hash = sha256(serialized);

  const files: Record<string, FileMeta> = {};
  for (const name of onDisk) {
    files[name] = fileMeta(name);
  }

  const version = {
    tag: git(['describe', '--tags', '--abbrev=0']) ?? 'unknown',
    commit: git(['rev-parse', 'HEAD']) ?? 'unknown',
    hash,
    generatedAt: git(['log', '-1', '--format=%cI']) ?? 'unknown',
    files,
  };

  return {
    snapshot: `${BANNER}export const CONTRACTS_SNAPSHOT: unknown = ${serialized}\n\nexport const CONTRACTS_SNAPSHOT_HASH = ${JSON.stringify(
      hash,
    )};\n`,
    version: `${BANNER}export const CONTRACTS_VERSION: unknown = ${JSON.stringify(
      version,
      null,
      2,
    )};\n`,
    hash,
  };
}

function currentContent(path: string): string {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}

function main(): void {
  const check = process.argv.includes('--check');
  const artifacts = buildArtifacts();

  const targets: Array<[string, string]> = [
    [SNAPSHOT_FILE, artifacts.snapshot],
    [VERSION_FILE, artifacts.version],
  ];

  if (check) {
    const stale = targets.filter(
      ([path, expected]) => currentContent(path) !== expected,
    );

    if (stale.length > 0) {
      console.error(
        `Contracts snapshot is out of date (hash ${artifacts.hash}).\n` +
          stale.map(([path]) => `  - ${path}`).join('\n') +
          '\nRun `pnpm run contracts:snapshot` and commit the result.',
      );
      process.exit(1);
    }

    console.log(`Contracts snapshot is up to date (hash ${artifacts.hash}).`);
    return;
  }

  mkdirSync(GENERATED_DIR, { recursive: true });
  for (const [path, content] of targets) {
    writeFileSync(path, content, 'utf8');
  }

  console.log(
    `Wrote contracts snapshot (hash ${artifacts.hash}) -> ${GENERATED_DIR}`,
  );
}

main();
